create table if not exists public.settings (
  setting_key text primary key,
  value text
);

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nama text not null default 'Administrator',
  nsm text
);

create table if not exists public.tahun_ajaran (
  id bigint generated by default as identity primary key,
  nama text not null,
  semester text not null default 'Ganjil',
  is_aktif boolean not null default false,
  created_at timestamptz default now(),
  unique (nama, semester)
);

create table if not exists public.guru (
  id bigint generated by default as identity primary key,
  tahun_ajaran_id bigint not null references public.tahun_ajaran (id) on delete cascade,
  nama text not null,
  nip text,
  no_karpeg text,
  nrg text,
  nuptk text,
  jk text,
  tempat_lahir text,
  tgl_lahir text,
  pendidikan text,
  status text default 'GTY',
  pangkat text,
  tmt_golongan text,
  tmt_guru text,
  jenis_guru text,
  instrumen text default 'GMP',
  mapel text,
  jam_mengajar integer not null default 0,
  tugas1 text,
  tugas2 text,
  tugas3 text,
  tmt_tugas text,
  lembaga_lain text,
  jam_lembaga_lain integer not null default 0,
  penilai_nama text,
  penilai_nip text,
  penilai_pangkat text,
  periode_awal text,
  periode_akhir text,
  tgl_penilaian text,
  tgl_laporan text,
  tahap text default 'Formatif',
  created_at timestamptz default now()
);

create table if not exists public.pkg_nilai (
  guru_id bigint not null references public.guru (id) on delete cascade,
  role text not null,
  k integer not null,
  i integer not null,
  skor integer not null,
  primary key (guru_id, role, k, i)
);

create table if not exists public.pkg_hadir (
  guru_id bigint not null references public.guru (id) on delete cascade,
  bulan integer not null,
  terlambat double precision default 0,
  pulang_cepat double precision default 0,
  tk double precision default 0,
  primary key (guru_id, bulan)
);

create table if not exists public.pkb (
  guru_id bigint not null references public.guru (id) on delete cascade,
  no integer not null,
  indikator text,
  unsur text,
  jenis text,
  kegiatan text,
  primary key (guru_id, no)
);

create table if not exists public.pkkm_nilai (
  tahun integer not null,
  penilai integer not null,
  sec text not null,
  u integer not null,
  i integer not null,
  skor integer not null,
  primary key (tahun, penilai, sec, u, i)
);

create index if not exists guru_tahun_idx on public.guru (tahun_ajaran_id);
create index if not exists pkg_nilai_guru_idx on public.pkg_nilai (guru_id);
create index if not exists pkkm_tahun_idx on public.pkkm_nilai (tahun);

