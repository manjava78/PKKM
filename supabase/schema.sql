create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, nama, nsm)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nama', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data->>'nsm', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.resync_ids()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  gmax bigint;
  tmax bigint;
begin
  select max(id) into gmax from public.guru;
  select max(id) into tmax from public.tahun_ajaran;
  if gmax is null then
    perform setval(pg_get_serial_sequence('public.guru', 'id'), 1, false);
  else
    perform setval(pg_get_serial_sequence('public.guru', 'id'), gmax, true);
  end if;
  if tmax is null then
    perform setval(pg_get_serial_sequence('public.tahun_ajaran', 'id'), 1, false);
  else
    perform setval(pg_get_serial_sequence('public.tahun_ajaran', 'id'), tmax, true);
  end if;
end;
$$;

grant execute on function public.resync_ids() to authenticated;

